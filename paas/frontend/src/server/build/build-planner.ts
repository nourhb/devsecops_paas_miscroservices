import { env } from "@/server/config/env";
export type BuildProvider = "jenkins" | "tekton";
export type BuildProfile = "node" | "python" | "java" | "static" | "custom";
export type BuildMode = "platform-template" | "custom-dockerfile";
export interface BuildPlanInput {
    language?: string | null;
    gitRepositoryUrl?: string | null;
    autoGenerateDockerfile?: boolean | null;
}
export interface ResolvedBuildPlan {
    provider: BuildProvider;
    profile: BuildProfile;
    mode: BuildMode;
    templateName: string;
    templateVersion: string;
    detectionReason: string;
    zeroConfig: boolean;
}
function includesAny(value: string, needles: string[]): boolean {
    return needles.some((needle) => value.includes(needle));
}
function detectProfile(input: BuildPlanInput): {
    profile: BuildProfile;
    detectionReason: string;
} {
    const language = String(input.language ?? "").trim().toLowerCase();
    const repo = String(input.gitRepositoryUrl ?? "").trim().toLowerCase();
    const combined = `${language} ${repo}`.trim();
    if (includesAny(combined, ["angular"])) {
        return {
            profile: "static",
            detectionReason: language ? `Detected Angular from stack "${input.language}" (nginx static on port 80).` : "Detected Angular-style repository metadata (nginx static on port 80)."
        };
    }
    if (includesAny(combined, ["next", "nestjs", "nest", "express"])) {
        return {
            profile: "node",
            detectionReason: language ? `Detected server-side Node stack "${input.language}".` : "Detected Node server repository metadata."
        };
    }
    if (includesAny(combined, ["react", "vue", "vite", "spa"]) && !includesAny(combined, ["nestjs", "nest", "express", "next"])) {
        return {
            profile: "static",
            detectionReason: language ? `Detected static web app "${input.language}" (build → nginx on port 80).` : "Detected static SPA repository metadata (nginx on port 80)."
        };
    }
    if (includesAny(combined, ["node", "javascript", "typescript"])) {
        return {
            profile: "node",
            detectionReason: language ? `Detected from stack "${input.language}".` : "Detected Node-style repository metadata."
        };
    }
    if (includesAny(combined, ["python", "django", "flask", "fastapi", "poetry", "pip"])) {
        return {
            profile: "python",
            detectionReason: language ? `Detected from stack "${input.language}".` : "Detected Python-style repository metadata."
        };
    }
    if (includesAny(combined, ["java", "spring", "maven", "gradle", "kotlin"])) {
        return {
            profile: "java",
            detectionReason: language ? `Detected from stack "${input.language}".` : "Detected JVM-style repository metadata."
        };
    }
    if (includesAny(combined, ["static", "html", "nginx", "frontend", "spa"])) {
        return {
            profile: "static",
            detectionReason: language ? `Detected from stack "${input.language}".` : "Detected static-site repository metadata."
        };
    }
    return {
        profile: "custom",
        detectionReason: language
            ? `No managed template matched stack "${input.language}", using custom mode.`
            : "No managed template matched the repository metadata, using custom mode."
    };
}
function templateNameFor(profile: BuildProfile, mode: BuildMode): string {
    if (mode === "custom-dockerfile") {
        return "repo-dockerfile";
    }
    switch (profile) {
        case "node":
            return "node-service";
        case "python":
            return "python-service";
        case "java":
            return "java-service";
        case "static":
            return "static-site";
        default:
            return "custom";
    }
}
export function resolveBuildProvider(): BuildProvider {
    return env.BUILD_BACKEND;
}
export function resolveBuildPlan(input: BuildPlanInput): ResolvedBuildPlan {
    const detected = detectProfile(input);
    const provider = resolveBuildProvider();
    const autoGenerateDockerfile = input.autoGenerateDockerfile !== false;
    const mode: BuildMode = detected.profile === "custom" || !autoGenerateDockerfile ? "custom-dockerfile" : "platform-template";
    return {
        provider,
        profile: detected.profile,
        mode,
        templateName: templateNameFor(detected.profile, mode),
        templateVersion: env.BUILD_TEMPLATE_VERSION,
        detectionReason: detected.detectionReason,
        zeroConfig: mode === "platform-template"
    };
}

const META_PREFIX = "[build-meta]";

export interface BuildRunMetadata {
    provider?: BuildProvider;
    profile?: BuildProfile;
    mode?: BuildMode;
    templateName?: string;
    templateVersion?: string;
    runId?: string | null;
    runNumber?: number | null;
    artifactImage?: string | null;
    artifactDigest?: string | null;
}

function normalizeMetaValue(value: string): string {
    return value.replace(/\s+/g, " ").trim();
}

export function buildMetadataLines(
    plan: ResolvedBuildPlan,
    metadata: Omit<BuildRunMetadata, "profile" | "mode" | "templateName" | "templateVersion" | "provider">
): string[] {
    const pairs: [string, string | number | null | undefined][] = [
        ["provider", plan.provider],
        ["profile", plan.profile],
        ["mode", plan.mode],
        ["templateName", plan.templateName],
        ["templateVersion", plan.templateVersion],
        ["runId", metadata.runId],
        ["runNumber", metadata.runNumber],
        ["artifactImage", metadata.artifactImage],
        ["artifactDigest", metadata.artifactDigest]
    ];
    return pairs
        .filter(([, value]) => value !== undefined && value !== null && String(value).trim() !== "")
        .map(([key, value]) => `${META_PREFIX} ${key}=${normalizeMetaValue(String(value))}`);
}

export function prependBuildMetadata(
    logs: string,
    plan: ResolvedBuildPlan,
    metadata: Omit<BuildRunMetadata, "profile" | "mode" | "templateName" | "templateVersion" | "provider">
): string {
    const lines = buildMetadataLines(plan, metadata);
    return lines.length > 0 ? `${lines.join("\n")}\n${logs}`.trim() : logs.trim();
}

export function parseBuildMetadata(logs: string | null | undefined): BuildRunMetadata {
    const metadata: BuildRunMetadata = {};
    for (const rawLine of String(logs ?? "").split("\n")) {
        const line = rawLine.trim();
        if (!line.startsWith(META_PREFIX)) {
            continue;
        }
        const payload = line.slice(META_PREFIX.length).trim();
        const [key, ...valueParts] = payload.split("=");
        const value = valueParts.join("=").trim();
        if (!key || !value) {
            continue;
        }
        switch (key.trim()) {
            case "provider":
                if (value === "jenkins" || value === "tekton") {
                    metadata.provider = value;
                }
                break;
            case "profile":
                if (["node", "python", "java", "static", "custom"].includes(value)) {
                    metadata.profile = value as BuildProfile;
                }
                break;
            case "mode":
                if (value === "platform-template" || value === "custom-dockerfile") {
                    metadata.mode = value;
                }
                break;
            case "templateName":
                metadata.templateName = value;
                break;
            case "templateVersion":
                metadata.templateVersion = value;
                break;
            case "runId":
                metadata.runId = value;
                break;
            case "runNumber": {
                const parsed = Number(value);
                metadata.runNumber = Number.isFinite(parsed) ? parsed : null;
                break;
            }
            case "artifactImage":
                metadata.artifactImage = value;
                break;
            case "artifactDigest":
                metadata.artifactDigest = value;
                break;
        }
    }
    return metadata;
}

export function formatArtifactReference(image: string | null | undefined, digest: string | null | undefined): string | null {
    if (!image) {
        return null;
    }
    return digest ? `${image}@${digest}` : image;
}

export interface DeployProfileSpec {
    profile: BuildProfile;
    containerPort: number;
    probePath: string;
}

export function resolveDeployProfileSpec(profile: BuildProfile): DeployProfileSpec {
    switch (profile) {
        case "python":
            return { profile, containerPort: 8000, probePath: "/" };
        case "java":
            return { profile, containerPort: 8080, probePath: "/" };
        case "static":
            return { profile, containerPort: 8080, probePath: "/" };
        case "node":
            return { profile, containerPort: 3000, probePath: "/" };
        default:
            return { profile: "custom", containerPort: 8080, probePath: "/" };
    }
}

export function resolveDeployProfileFromProject(input: BuildPlanInput): DeployProfileSpec {
    const plan = resolveBuildPlan(input);
    return resolveDeployProfileSpec(plan.profile);
}
